const formatKeyword = (keyword: string) => {
  if (keywordDisplayMap[keyword]) return keywordDisplayMap[keyword];
  return keyword
    .split(/\s+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(" ");
};

